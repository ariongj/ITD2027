# ----------------------------------------------------------------- helpers
def attr(s):
    return html.escape(str(s), quote=True)


def icon(name, cls="icon"):
    if name == "whatsapp":
        return (f'<svg class="{cls}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" focusable="false">'
                f'<path d="{WA_PATH}"/></svg>')
    return (f'<svg class="{cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" '
            f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">{STROKE_ICONS[name]}</svg>')


def wa_url(text=""):
    return WA + ("?text=" + urllib.parse.quote(text) if text else "")


def btn_wa(label, text="", cls="btn btn-secondary"):
    return (f'<a class="{cls}" href="{wa_url(text)}" target="_blank" rel="noopener noreferrer">'
            f'{icon("whatsapp")}<span>{label}</span></a>')


def btn_cal(label, cls="btn btn-primary"):
    return (f'<a class="{cls}" href="{CAL}" target="_blank" rel="noopener noreferrer">'
            f'{icon("calendar")}<span>{label}</span></a>')


def btn(label, href, cls="btn btn-primary", arrow=False):
    return f'<a class="{cls}" href="{href}"><span>{label}</span>{icon("arrow") if arrow else ""}</a>'


def link_arrow(label, href):
    return f'<a class="link-arrow" href="{href}">{label}{icon("arrow")}</a>'


def section_head(eyebrow, h2, lead=None, cls=""):
    lead_html = f'<p class="section-lead">{lead}</p>' if lead else ""
    return f'<div class="section-head {cls}"><p class="eyebrow">{eyebrow}</p><h2>{h2}</h2>{lead_html}</div>'


def check_list(items, cls="check-list"):
    return f'<ul class="{cls}">' + "".join(f'<li>{icon("check")}<span>{i}</span></li>' for i in items) + "</ul>"


def dot_list(items, cls="dot-list"):
    return f'<ul class="{cls}">' + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


def chips(items):
    return '<ul class="chips">' + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


def steps(items, cls="steps"):
    out = [f'<ol class="{cls} stagger">']
    for i, s in enumerate(items, 1):
        out.append(f'<li class="step reveal"><span class="step-num">{i:02d}</span><h3>{s["title"]}</h3><p>{s["text"]}</p></li>')
    out.append("</ol>")
    return "".join(out)


def stats(items):
    out = ['<div class="stats stagger">']
    for s in items:
        out.append(f'<div class="stat reveal"><span class="stat-value">{s["value"]}</span>'
                   f'<span class="stat-label">{s["label"]}</span><span class="stat-text">{s["text"]}</span></div>')
    out.append("</div>")
    return "".join(out)


