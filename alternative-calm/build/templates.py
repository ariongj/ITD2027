def lang_switch(L, ALL, key, cls="lang-switch"):
    out = [f'<div class="{cls}" role="group" aria-label="{attr(L["ui"]["langLabel"])}">']
    for lang in LANGS:
        active = lang == L["lang"]
        href = ALL[lang]["urls"][key]
        cur = ' aria-current="true"' if active else ""
        out.append(f'<a class="lang-option{" is-active" if active else ""}" href="{href}" hreflang="{lang}" lang="{lang}"{cur}>{lang.upper()}</a>')
    out.append("</div>")
    return "".join(out)


