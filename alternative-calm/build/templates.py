def jsonld(L, key, title, desc):
    url = SITE + L["urls"][key]
    home = SITE + L["urls"]["home"]
    crumbs = [{"@type": "ListItem", "position": 1, "name": "IT Department", "item": home}]
    if key != "home":
        parent = PARENT.get(key)
        if parent:
            crumbs.append({"@type": "ListItem", "position": 2, "name": L[parent]["crumb"], "item": SITE + L["urls"][parent]})
        crumbs.append({"@type": "ListItem", "position": len(crumbs) + 1,
                       "name": L[key].get("crumb") or title.split("|")[0].strip(), "item": url})
    graph = [ORG, WEBSITE,
             {"@type": "BreadcrumbList", "@id": url + "#breadcrumb", "itemListElement": crumbs},
             {"@type": "WebPage", "@id": url + "#webpage", "url": url, "name": title, "description": desc,
              "isPartOf": {"@id": SITE + "/#website"}, "about": {"@id": SITE + "/#organization"},
              "publisher": {"@id": SITE + "/#organization"}, "primaryImageOfPage": SITE + "/assets/brand/" + OG_FILES[L["lang"]],
              "inLanguage": L["lang"], "dateModified": TODAY, "breadcrumb": {"@id": url + "#breadcrumb"}}]
    if key == "about":
        graph.append({"@type": "FAQPage", "@id": url + "#faq", "mainEntity": [
            {"@type": "Question", "name": q["q"], "acceptedAnswer": {"@type": "Answer", "text": q["a"]}}
            for q in L["about"]["faq"]["items"]]})
    data = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False).replace("</", "<\\/")
    return f'<script type="application/ld+json">{data}</script>'


